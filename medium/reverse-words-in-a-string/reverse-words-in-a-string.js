// решение 1
// время O(n)
// память O(n)

// split(" ") — разбивает строку на массив (в т.ч. включает пустые строки из-за нескольких пробелов).
// filter(...) — оставляет только непустые слова.
// reverse() — инвертирует порядок слов.
// join(" ") — собирает обратно в строку, разделяя слова одним пробелом.
var reverseWords = function(s) {
return s
    .split(" ")          // Разделяем по пробелам
    .filter(word => word.length > 0)  // Убираем пустые строки
    .reverse()           // Переворачиваем порядок слов
    .join(" ");          // Склеиваем обратно через пробел
};
  


// решение 2
// время O(n²)
// память O(n)

// Цикл for (let i = sArr.length - 1; i >= 0; i--) → O(k * m)
// — здесь ты выполняешь конкатенацию строк в цикле, что в JS может быть дорогой операцией
// т.к. строки в JS — иммутабельны, и при каждом reversedStr += word создается новая строка

// В худшем случае — это:

// scss
// Копировать
// Редактировать
// "" + word1 → O(len(word1))
// then that + word2 → O(len(word1) + len(word2))
// ...
// — приводит к O(n²) времени, если много слов.

// ⚠️ Ключевой момент:
// Если ты конкатенируешь строки через +=, это может быть квадратично.

// Лучше использовать массив + join(' ').
var reverseWords = function(s) {
    const sArr = s.trim().split(' ').filter(word => word !== '');
    let reversedStr = '';
    for (let i = sArr.length - 1; i >= 0; i--) {
        const word = sArr[i];
        reversedStr += word;
        if (i !== 0) {
            reversedStr += ' ';
        }
    }
    return reversedStr;
};