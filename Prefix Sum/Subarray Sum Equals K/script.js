// В нашей задаче Map будет хранить:

// ключ = сумма, которая уже встречалась (префиксная сумма)

// значение = сколько раз такая сумма уже была

function subarraySum(nums, k) {
    const map = new Map();
    map.set(0, 1);  // важный шаг: сумма 0 считается как 1 раз встречена
    let sum = 0;    // это наша текущая сумма
    let count = 0;  // сколько подмассивов нашли

    for (let num of nums) {
        sum += num;  // обновляем текущую сумму

        // проверим, была ли сумма sum - k ранее
        if (map.has(sum - k)) {
            count += map.get(sum - k);  // увеличим количество подходящих подмассивов
        }

        // запомним, что сумма `sum` встретилась ещё раз
        map.set(sum, (map.get(sum) || 0) + 1);
    }

    return count;
}